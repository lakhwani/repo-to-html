#!/usr/bin/env python3
"""
Repository to HTML Converter
This script takes a repository directory, traverses all files, and generates
an HTML document containing each file's path and content.
"""
import os
import json
import argparse
import html
import datetime

DEFAULT_CONFIG = {
    "excluded_extensions": [
        ".git",
        ".pyc",
        ".class",
        ".o",
        ".exe",
        ".pdf",
        ".jpg",
        ".jpeg",
        ".png",
        ".gif",
        ".ico",
        ".svg",
        ".webp",
        ".bmp",
        ".ttf",
        ".woff",
        ".woff2",
        ".eot",
        ".map",
        ".lock",
    ],
    "excluded_folders": [
        ".git",
        "__pycache__",
        "node_modules",
        "venv",
        "dist",
        "build",
        ".next",
        "out",
        ".vercel",
        ".cache",
        "public/images",
        "public/static",
        "coverage",
        ".vscode",
        "repo-export"
    ],
    "excluded_files": ["pnpm-lock.yaml", ".env.local"],
    "title": "Repository Code Documentation",
    "max_file_size_kb": 500,  # Skip files larger than this size (in KB)
}

